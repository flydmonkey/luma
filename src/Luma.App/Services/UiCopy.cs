    private static string _lang = UiLanguages.ZhHans;

    public static string Lang => _lang;

    public static void SetLanguage(string resolved)
    {
        _lang = string.IsNullOrWhiteSpace(resolved) ? UiLanguages.En : resolved;
        try
        {
            ApplicationLanguages.PrimaryLanguageOverride = UiLanguages.FrameworkTag(_lang);
        }
        catch
        {
            // Unpackaged hosts can ignore the override; in-app tables still apply.
        }
    }

    public static string T(string key)
    {
        if (Tables.TryGetValue(_lang, out var table) && table.TryGetValue(key, out var value))
        {
            return value;
        }

        if (Tables[UiLanguages.En].TryGetValue(key, out var en))
        {
            return en;
        }

        return key;
    }

    public static string Tf(string key, params object[] args)
        => string.Format(T(key), args);

